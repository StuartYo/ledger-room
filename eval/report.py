"""Render eval/RESULTS.md and the README results block from eval/results.json (never by hand).

python -m eval.report
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from ledger_room.rules import ISSUE_TYPES

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- RESULTS:START (generated by eval/report.py from eval/results.json) -->", "<!-- RESULTS:END -->"
SHORT = {"UBN_CHECKSUM": "UBN checksum", "DUP_CROSS_MONTH": "Duplicate, same client",
         "DUP_CROSS_CLIENT": "Duplicate, across clients", "S19_NONDEDUCTIBLE": "Art. 19 non-deductible",
         "OVER_LIMIT": "Over policy limit", "PERIOD_MISMATCH": "Period mismatch"}


def pct(x):
    return "n/a" if x is None else f"{x * 100:.0f}%"


def f2(x):
    return "n/a" if x is None else f"{x:.2f}"


def load() -> dict:
    return json.loads((ROOT / "eval" / "results.json").read_text(encoding="utf-8"))


def readme_block(R: dict) -> str:
    rows = []
    for s, v in R["sets"].items():
        lr, pm = v["ledger_room"], v.get("pure_model")
        rows.append(f"| {s} ({v['n_docs']} docs, layout {v['layout_family']}) | "
                    f"{f2(lr['micro']['f1'])} (P {pct(lr['micro']['precision'])}, R {pct(lr['micro']['recall'])}) | "
                    + (f"{f2(pm['micro']['f1'])} (P {pct(pm['micro']['precision'])}, R {pct(pm['micro']['recall'])}) | "
                       if pm else "not run | ")
                    + f"{lr['sec_per_doc']['mean'] if lr['sec_per_doc'] else 'n/a'} s |")
    pc = R["positive_control"]
    ms = R["model_selection"]
    sel = [f"| {v['config']} | {v['sec_per_doc']} s | {'yes' if v['used'] else 'no'} |" for v in ms["vlm"]] + \
          [f"| OCR: {v['config']} | {v['sec_per_page']} s | {'yes' if v['used'] else 'no'} |" for v in ms["ocr"]]
    return "\n".join([
        START,
        "Synthetic data. Same local model (Qwen3.5-2B INT4, OpenVINO) on the same photo + OCR text in both columns; "
        "the pure model gets the rules in its prompt but no code checks.",
        "",
        "| Set | Ledger Room micro F1 | Pure model micro F1 | Ledger Room s/doc (laptop iGPU) |",
        "|---|---|---|---|",
        *rows,
        "",
        f"Positive control: {pc['after_detected']}/{pc['after_planted']} planted changes detected, "
        f"{pc['after_false_flags']} false flags after, {pc['before_flags']} flags before. "
        f"Gate (stop if pure model >= {R['gate_threshold']:.0%} of Ledger Room): "
        f"max ratio {f2(R['gate']['max_ratio'])}, {'STOP' if R['gate']['stop'] else 'pass'}. "
        "Details: [eval/RESULTS.md](eval/RESULTS.md).",
        "",
        f"Runtime choice, measured on {ms['measured_on']} ({ms['hardware']}):",
        "",
        "| Configuration | Time per document | Used |",
        "|---|---|---|",
        *sel,
        END,
    ])


def results_md(R: dict) -> str:
    L = ["# Ledger Room evaluation results", "",
         "> Generated by `python -m eval.report` from `eval/results.json`. Do not edit by hand.",
         "> **All documents are synthetic** (drawn by `synth/generate.py`). Numbers describe this synthetic benchmark only.",
         "",
         f"- Generated: {R['generated_at']} (code {R['code_rev']}, reader {R['reader_version']})",
         f"- Model: {R['model']}",
         f"- Runtime: {R['runtime']}",
         f"- Hardware: {R['hardware']}",
         "",
         "## What is compared",
         "",
         "- **Ledger Room**: OCR + the model transcribe each document; deterministic code applies the six rules "
         "(UBN checksum, duplicates within a client and across clients, VAT Act Art. 19, client policy limits, filing period).",
         "- **Pure model**: the same model, same photo, same OCR lines, with the six rules, the client's policy and the filing "
         "period written into the prompt. For duplicates it gets a running list of the documents it already reviewed, "
         "built from its own earlier answers. No code checks.",
         "- **Oracle control**: the rule engine fed the ground-truth fields (no model). It must score 100%; it proves the "
         "answer key and the rules agree, and isolates reading errors.",
         "- **Positive control**: a clean batch, then the same batch with one planted change per issue type, run through the full stack.",
         "",
         "Held-out set: different seed, different clients, different layouts (family B: other fonts, column order, "
         "landscape receipts, stronger photo effects). Its answers were committed before any prompt or code tuning; "
         "tuning used the main set only.",
         ""]
    for s, v in R["sets"].items():
        lr, pm = v["ledger_room"], v.get("pure_model")
        L += [f"## Set `{s}`: {v['n_docs']} documents, {v['n_clients']} clients, layout family {v['layout_family']}", "",
              "| | Ledger Room | Pure model |", "|---|---|---|",
              f"| Micro precision | {pct(lr['micro']['precision'])} | {pct(pm['micro']['precision']) if pm else 'n/a'} |",
              f"| Micro recall | {pct(lr['micro']['recall'])} | {pct(pm['micro']['recall']) if pm else 'n/a'} |",
              f"| Micro F1 | {f2(lr['micro']['f1'])} | {f2(pm['micro']['f1']) if pm else 'n/a'} |",
              f"| Documents with exactly the right flags | {lr['docs_exact']}/{lr['n_docs']} | "
              f"{(str(pm['docs_exact']) + '/' + str(pm['n_docs'])) if pm else 'n/a'} |",
              f"| Clean documents wrongly flagged | {lr['clean_docs_flagged']}/{lr['clean_docs']} | "
              f"{(str(pm['clean_docs_flagged']) + '/' + str(pm['clean_docs'])) if pm else 'n/a'} |",
              f"| Seconds per document (mean / max) | {lr['sec_per_doc']['mean']} / {lr['sec_per_doc']['max']} | "
              f"{(str(pm['sec_per_doc']['mean']) + ' / ' + str(pm['sec_per_doc']['max'])) if pm and pm['sec_per_doc'] else 'n/a'} |",
              "", "Per issue type (recall = found / planted; precision = correct / flagged):", "",
              "| Issue | Planted | Ledger Room recall | Ledger Room precision | Pure model recall | Pure model precision |",
              "|---|---|---|---|---|---|"]
        for t in ISSUE_TYPES:
            a = lr["per_type"][t]
            b = pm["per_type"][t] if pm else None
            L.append(f"| {SHORT[t]} | {v['issue_counts'][t]} | {pct(a['recall'])} | {pct(a['precision'])} | "
                     f"{pct(b['recall']) if b else 'n/a'} | {pct(b['precision']) if b else 'n/a'} |")
        L += ["", f"Oracle control (rules on ground-truth fields): F1 {f2(v['oracle_fields']['f1'])}. "
              f"Rule engine time for the whole set: {lr['rules_ms_total']} ms. "
              f"Fields the reader could not read and routed to a human: {lr['unreadable_fields']}."
              + (f" Pure-model replies that were not valid JSON: {pm['unparsed_replies']}." if pm else ""), ""]
        if v.get("pure_over_ledger_f1") is not None:
            L += [f"Pure model F1 / Ledger Room F1 = {f2(v['pure_over_ledger_f1'])}.", ""]
    pc = R["positive_control"]
    L += ["## Positive control", "",
          f"- Clean batch: {pc['before_flags']} flags (expected 0).",
          f"- Same batch plus one planted change per issue type: {pc['after_detected']}/{pc['after_planted']} detected, "
          f"{pc['after_false_flags']} false flags.",
          "", "## Gate", "",
          f"{R['gate']['rule']}. Max ratio {f2(R['gate']['max_ratio'])}: "
          f"{'STOP - the pure model is close enough that the system adds little.' if R['gate']['stop'] else 'pass.'}",
          "", "## Limits", "",
          "- Synthetic documents only; real phone photos, handwriting and faded thermal paper will be harder.",
          "- The laptop timing uses the Intel UHD iGPU; Arc Pro B70 timings are not measured yet.",
          "- The planted issues were designed by the author; the held-out set changes seed, clients and layouts but "
          "not the issue definitions.",
          ""]
    return "\n".join(L)


def write():
    R = load()
    (ROOT / "eval" / "RESULTS.md").write_text(results_md(R), encoding="utf-8")
    rp = ROOT / "README.md"
    txt = rp.read_text(encoding="utf-8")
    block = readme_block(R)
    if START in txt and END in txt:
        txt = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, txt, flags=re.S)
    else:
        txt = txt.rstrip() + "\n\n## Results\n\n" + block + "\n"
    rp.write_text(txt, encoding="utf-8")
    print("wrote eval/RESULTS.md and README block")


if __name__ == "__main__":
    write()
