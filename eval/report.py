"""Render eval/RESULTS.md and the README results block from eval/results.json (never by hand).

python -m eval.report
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from ledger_room.rules import ISSUE_TYPES

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- RESULTS:START (generated by eval/report.py from eval/results.json) -->", "<!-- RESULTS:END -->"
SHORT = {"UBN_CHECKSUM": "UBN checksum", "DUP_CROSS_MONTH": "Duplicate, same client",
         "DUP_CROSS_CLIENT": "Duplicate, across clients", "S19_NONDEDUCTIBLE": "Art. 19 non-deductible",
         "OVER_LIMIT": "Over policy limit", "PERIOD_MISMATCH": "Period mismatch"}


def pct(x):
    return "n/a" if x is None else f"{x * 100:.0f}%"


def f2(x):
    """Two decimals, half up (0.175 -> 0.18), so README, deck and video round the same way."""
    if x is None:
        return "n/a"
    from decimal import ROUND_HALF_UP, Decimal
    return str(Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def load() -> dict:
    return json.loads((ROOT / "eval" / "results.json").read_text(encoding="utf-8"))


def blind_lines(R: dict) -> list[str]:
    B = R.get("blind_first_run")
    if not B or "heldout" not in B["sets"]:
        return []
    h = B["sets"]["heldout"]
    return [f"**Held-out, first blind run** (code {B['code_rev']}, before any change made after seeing held-out errors): "
            f"Ledger Room F1 {f2(h['ledger_room']['f1'])} (P {pct(h['ledger_room']['precision'])}, "
            f"R {pct(h['ledger_room']['recall'])}), pure model F1 {f2(h['pure_model']['f1'])}. "
            f"The table above uses later code with {R.get('fixes_after_blind', 'some')} fixes made after that run "
            "(listed in eval/RESULTS.md), so its held-out row is no longer blind.", ""]


def larger_lines(R: dict) -> list[str]:
    """2B vs larger reader on the held-out set (markdown table + one sentence)."""
    L = R.get("larger_model")
    h = R["sets"].get("heldout")
    if not L or not h:
        return []
    lr2, pm2, rd2 = h["ledger_room"], h.get("pure_model"), h["ledger_room"].get("reading")
    lr9, pm9, rd9 = L["ledger_room"], L["pure_model"], L["reading"]

    def row(name, lr, pm, rd, sp):
        return (f"| {name} | {f2(lr['micro']['f1'])} | {f2(pm['micro']['f1']) if pm else 'n/a'} | "
                f"{pct(rd['field_error_rate']) if rd else 'n/a'} ({rd['fields_wrong']}/{rd['fields_compared']}) | "
                f"{rd['docs_items_right']}/{rd['docs']} | {sp} s |")
    RM = R.get("reader_memory", {})
    mem = RM.get(L["model"]) or L.get("memory", {})
    mem2 = RM.get(R["model"].split(" ")[0], {})
    cpu = L.get("cpu_sample")
    return [
        f"**Does a bigger model alone close the gap?** Held-out set (frozen key, no tuning), same laptop, "
        f"{L['model']} on {L['device']}:",
        "",
        "| Reader | Ledger Room F1 | Pure model F1 | Reading error rate (key fields wrong) | Docs with all item lines right | Read time per document |",
        "|---|---|---|---|---|---|",
        row(R["model"].split(" ")[0], lr2, pm2, rd2, lr2["sec_per_doc"]["mean"]),
        row(L["model"], lr9, pm9, rd9, lr9["sec_per_doc"]["mean"]),
        "",
        f"Key fields: type, invoice number, date, seller and buyer UBN, net, tax, total. Thinking mode off for both. "
        f"The 9B ran on the laptop CPU because compiling it for the iGPU ran out of memory (the iGPU shares system RAM). "
        f"On disk: 2B {mem2.get('disk_gb', 'n/a')} GB, 9B {L['model_on_disk_gb']} GB. Peak RAM in use (working set, "
        f"eval/measure_reader.py): 2B on the iGPU {mem2.get('peak_working_set_gb', 'n/a')} GB, 9B on the CPU "
        f"{mem.get('peak_working_set_gb', 'n/a')} GB. 9B on the laptop CPU: about {L['docs_per_hour']} documents per hour.",
        "",
    ]


def amount_lines(R: dict) -> list[str]:
    h = R["sets"].get("heldout", {}).get("ledger_room", {})
    rd, rf = h.get("reading"), h.get("routing_flags")
    if not rd or "amount_check" not in rd:
        return []
    a = rd["amount_check"]
    pf = rd["per_field"]
    return [f"**Amounts.** The 2B reader gets every identifier right after OCR snapping but misreads amounts (held-out: "
            f"net {pf['net']}, tax {pf['tax']}, total {pf['total']} wrong). The amount rule (net + tax = total, tax = 5% "
            f"of net, both read on a deductible voucher) holds {a['held_by_amount_rule']} of the "
            f"{a['docs_with_amount_error']} documents with a materially wrong or missing amount, and "
            f"{a['held_with_correct_amounts']} documents whose amounts were right. Routing flags on held-out: "
            + ", ".join(f"{k} {v}" for k, v in rf.items()) + ".", ""]


def einvoice_lines(R: dict) -> list[str]:
    E = R.get("einvoice_check")
    if not E:
        return []
    asif = E["rule_exceptions_as_if_issued_to_a_company"].get("S19_NONDEDUCTIBLE", 0)
    return [f"**Real data, import path only (no OCR):** one person's own consumer e-invoices exported from the MOF "
            f"platform ({E['months']} months; not a bookkeeping firm's client data; aggregates only). "
            f"{E['invoices']} invoices / {E['line_items']} line items imported "
            f"({E['invoices_with_discount_lines']} with discount lines, {E['invoices_with_zero_price_lines']} with "
            f"zero-price lines). Seller UBNs passing the 2023 checksum: {E['seller_ubn_pass_2023_rule']} "
            f"({E['sellers_failing_old_mod10_rule']} of them would fail an outdated mod-10 checker). "
            f"Duplicates: {E['duplicates_found']}. Art. 19 keyword hits: {asif} invoices (alcohol); "
            f"meal invoices: {E['expense_category'].get('meal', 0)}. "
            f"Import plus rules: {E['ms_per_invoice_import_plus_rules']} ms per invoice.", ""]


def readme_block(R: dict) -> str:
    rows = []
    for s, v in R["sets"].items():
        lr, pm = v["ledger_room"], v.get("pure_model")
        rows.append(f"| {s} ({v['n_docs']} docs, layout {v['layout_family']}) | "
                    f"{f2(lr['micro']['f1'])} (P {pct(lr['micro']['precision'])}, R {pct(lr['micro']['recall'])}) | "
                    + (f"{f2(pm['micro']['f1'])} (P {pct(pm['micro']['precision'])}, R {pct(pm['micro']['recall'])}) | "
                       if pm else "not run | ")
                    + f"{lr['sec_per_doc']['mean'] if lr['sec_per_doc'] else 'n/a'} s |")
    pc = R["positive_control"]
    ms = R["model_selection"]
    sel = [f"| {v['config']} | {v['sec_per_doc']} s | {'yes' if v['used'] else 'no'} |" for v in ms["vlm"]] + \
          [f"| OCR: {v['config']} | {v['sec_per_page']} s | {'yes' if v['used'] else 'no'} |" for v in ms["ocr"]]
    return "\n".join([
        START,
        "Synthetic data. Same local model (Qwen3.5-2B INT4, OpenVINO) on the same photo + OCR text in both columns; "
        "the pure model gets the rules in its prompt but no code checks.",
        "",
        "| Set | Ledger Room micro F1 | Pure model micro F1 | Read time per document (laptop iGPU) |",
        "|---|---|---|---|",
        *rows,
        "",
        *blind_lines(R),
        *amount_lines(R),
        *larger_lines(R),
        *einvoice_lines(R),
        f"Positive control: {pc['after_detected']}/{pc['after_planted']} planted changes detected, "
        f"{pc['after_false_flags']} false flags after, {pc['before_flags']} flags before. "
        f"Gate (stop if pure model >= {R['gate_threshold']:.0%} of Ledger Room): "
        f"max ratio {f2(R['gate']['max_ratio'])}, {'STOP' if R['gate']['stop'] else 'pass'}. "
        "Details: [eval/RESULTS.md](eval/RESULTS.md).",
        "",
        f"Runtime choice, measured on {ms['measured_on']} ({ms['hardware']}):",
        "",
        "| Configuration | Time per document | Used |",
        "|---|---|---|",
        *sel,
        END,
    ])


def results_md(R: dict) -> str:
    L = ["# Ledger Room evaluation results", "",
         "> Generated by `python -m eval.report` from `eval/results.json`. Do not edit by hand.",
         "> **All documents are synthetic** (drawn by `synth/generate.py`). Numbers describe this synthetic benchmark only.",
         "",
         f"- Generated: {R['generated_at']} (code {R['code_rev']}, reader {R['reader_version']})",
         f"- Model: {R['model']}",
         f"- Runtime: {R['runtime']}",
         f"- Hardware: {R['hardware']}",
         "",
         "## What is compared",
         "",
         "- **Ledger Room**: OCR + the model transcribe each document; deterministic code applies the six rules "
         "(UBN checksum, duplicates within a client and across clients, VAT Act Art. 19, client policy limits, filing period).",
         "- **Pure model**: the same model, same photo, same OCR lines, with the six rules, the client's policy and the filing "
         "period written into the prompt. For duplicates it gets a running list of the documents it already reviewed, "
         "built from its own earlier answers. No code checks.",
         "- **Oracle control**: the rule engine fed the ground-truth fields (no model). It must score 100%; it proves the "
         "answer key and the rules agree, and isolates reading errors.",
         "- **Positive control**: a clean batch, then the same batch with one planted change per issue type, run through the full stack.",
         "",
         "Held-out set: different seed, different clients, different layouts (family B: other fonts, column order, "
         "landscape receipts, stronger photo effects). Its answers were committed before any prompt or code tuning; "
         "tuning used the main set only. After the first evaluation, four fixes were made (one prompted by a held-out "
         "error, one by the positive control); the blind numbers from before them are kept below under \"First blind run\".",
         ""]
    for s, v in R["sets"].items():
        lr, pm = v["ledger_room"], v.get("pure_model")
        L += [f"## Set `{s}`: {v['n_docs']} documents, {v['n_clients']} clients, layout family {v['layout_family']}", "",
              "| | Ledger Room | Pure model |", "|---|---|---|",
              f"| Micro precision | {pct(lr['micro']['precision'])} | {pct(pm['micro']['precision']) if pm else 'n/a'} |",
              f"| Micro recall | {pct(lr['micro']['recall'])} | {pct(pm['micro']['recall']) if pm else 'n/a'} |",
              f"| Micro F1 | {f2(lr['micro']['f1'])} | {f2(pm['micro']['f1']) if pm else 'n/a'} |",
              f"| Documents with exactly the right flags | {lr['docs_exact']}/{lr['n_docs']} | "
              f"{(str(pm['docs_exact']) + '/' + str(pm['n_docs'])) if pm else 'n/a'} |",
              f"| Clean documents wrongly flagged | {lr['clean_docs_flagged']}/{lr['clean_docs']} | "
              f"{(str(pm['clean_docs_flagged']) + '/' + str(pm['clean_docs'])) if pm else 'n/a'} |",
              f"| Seconds per document (mean / max) | {lr['sec_per_doc']['mean']} / {lr['sec_per_doc']['max']} | "
              f"{(str(pm['sec_per_doc']['mean']) + ' / ' + str(pm['sec_per_doc']['max'])) if pm and pm['sec_per_doc'] else 'n/a'} |",
              "", "Per issue type (recall = found / planted; precision = correct / flagged):", "",
              "| Issue | Planted | Ledger Room recall | Ledger Room precision | Pure model recall | Pure model precision |",
              "|---|---|---|---|---|---|"]
        for t in ISSUE_TYPES:
            a = lr["per_type"][t]
            b = pm["per_type"][t] if pm else None
            L.append(f"| {SHORT[t]} | {v['issue_counts'][t]} | {pct(a['recall'])} | {pct(a['precision'])} | "
                     f"{pct(b['recall']) if b else 'n/a'} | {pct(b['precision']) if b else 'n/a'} |")
        L += ["", f"Oracle control (rules on ground-truth fields): F1 {f2(v['oracle_fields']['f1'])}. "
              f"Rule engine time for the whole set: {lr['rules_ms_total']} ms. "
              f"Fields read by the model but not confirmed on the page: {lr['unreadable_fields']}; "
              f"review items raised: {lr.get('review_items', 0)}."
              + (f" Pure-model replies that were not valid JSON: {pm['unparsed_replies']}." if pm else ""), ""]
        rd = lr.get("reading")
        if rd:
            L += [f"Reading (fields Ledger Room ends up with, against the key): {pct(rd['field_error_rate'])} of key fields "
                  f"wrong ({rd['fields_wrong']}/{rd['fields_compared']}); documents with every key field right "
                  f"{rd['docs_all_key_fields_right']}/{rd['docs']}; with every item line right {rd['docs_items_right']}/{rd['docs']}. "
                  "Per field: " + ", ".join(f"{k} {x}" for k, x in rd["per_field"].items()) + ".", ""]
        if v.get("pure_over_ledger_f1") is not None:
            L += [f"Pure model F1 / Ledger Room F1 = {f2(v['pure_over_ledger_f1'])}.", ""]
    B = R.get("blind_first_run")
    if B:
        L += ["## First blind run", "", B["note"], "",
              f"Code {B['code_rev']}, reader {B['reader_version']}, {B['generated_at']}.", "",
              "| Set | Ledger Room F1 (P / R) | Pure model F1 (P / R) | Ledger Room exact documents | Clean documents wrongly flagged |",
              "|---|---|---|---|---|"]
        for s, v in B["sets"].items():
            a, b = v["ledger_room"], v["pure_model"]
            L.append(f"| {s} | {f2(a['f1'])} ({pct(a['precision'])} / {pct(a['recall'])}) | "
                     f"{f2(b['f1'])} ({pct(b['precision'])} / {pct(b['recall'])}) | {v['ledger_docs_exact']}/{v['n_docs']} | "
                     f"{v['ledger_clean_flagged']}/{v['clean_docs']} |")
        bpc = B["positive_control"]
        L += ["", f"Positive control in that run: {bpc['after_detected']}/{bpc['after_planted']} detected, "
              f"{bpc['after_false_flags']} false flag(s), {bpc['before_flags']} flags on the clean batch.", "",
              f"Bugs found by reading those errors and fixed afterwards ({R.get('fixes_after_blind', '')}):", ""]
        L += [f"- {x}" for x in R.get("fixes_after_blind_detail", [])]
        L += [""]
    LG = larger_lines(R)
    if LG:
        LM = R["larger_model"]
        L += ["## Larger reader on the held-out set", "",
              f"Generated {LM['generated_at']} (code {LM['code_rev']}). Same code, same rules, same prompts; only the "
              "model folder changes. The pure-model baseline is rerun with the larger model.", "", *LG,
              "Reading errors per field (wrong / compared): 2B " +
              ", ".join(f"{k} {v}" for k, v in R["sets"]["heldout"]["ledger_room"]["reading"]["per_field"].items()) +
              f"; {LM['model']} " + ", ".join(f"{k} {v}" for k, v in LM["reading"]["per_field"].items()) + ".", ""]
    EL = einvoice_lines(R)
    if EL:
        L += ["## Real e-invoice import check", "", *EL]
    pc = R["positive_control"]
    L += ["## Positive control", "",
          f"- Clean batch: {pc['before_flags']} flags (expected 0).",
          f"- Same batch plus one planted change per issue type: {pc['after_detected']}/{pc['after_planted']} detected, "
          f"{pc['after_false_flags']} false flags.",
          "", "## Gate", "",
          f"{R['gate']['rule']}. Max ratio {f2(R['gate']['max_ratio'])}: "
          f"{'STOP - the pure model is close enough that the system adds little.' if R['gate']['stop'] else 'pass.'}",
          "", "## Limits", "",
          "- Synthetic documents only; real phone photos, handwriting and faded thermal paper will be harder.",
          "- The laptop timing uses the Intel UHD iGPU; Arc Pro B70 timings are not measured yet.",
          "- The planted issues were designed by the author; the held-out set changes seed, clients and layouts but "
          "not the issue definitions.",
          ""]
    return "\n".join(L)


def write():
    R = load()
    (ROOT / "eval" / "RESULTS.md").write_text(results_md(R), encoding="utf-8")
    rp = ROOT / "README.md"
    txt = rp.read_text(encoding="utf-8")
    block = readme_block(R)
    if START in txt and END in txt:
        txt = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, txt, flags=re.S)
    else:
        txt = txt.rstrip() + "\n\n## Results\n\n" + block + "\n"
    rp.write_text(txt, encoding="utf-8")
    print("wrote eval/RESULTS.md and README block")


if __name__ == "__main__":
    write()
