def wood(size, rng):
    W, H = size
    base = Image.new("RGB", (W, H), (150, 112, 74))
    d = ImageDraw.Draw(base)
    y = 0
    while y < H:
        h = rng.randint(3, 9)
        c = rng.randint(-22, 18)
        d.rectangle([0, y, W, y + h], fill=(150 + c, 112 + c, 74 + c // 2))
        y += h
    small = (max(1, W // 3), max(1, H // 3))      # seeded noise (Image.effect_noise is not seeded)
    noise = Image.frombytes("L", small, rng.randbytes(small[0] * small[1])).resize((W, H)).convert("RGB")
    return Image.blend(base, noise, 0.07).filter(ImageFilter.GaussianBlur(1.2))


def photograph(img: Image.Image, doc: dict) -> Image.Image:
    """Mild capture effects (this set tests rules, not legibility): scanner bed, desk photo or photocopy."""
    rng = random.Random(doc["photo_seed"])
    kind = doc["photo_kind"]
