def half_up(x: Decimal) -> int:
    return int(x.quantize(D("1"), rounding=ROUND_HALF_UP))


def amounts(mode: str, items) -> tuple:
    gross = sum(i["amount"] for i in items)
    if mode == "pretax":
        tax = half_up(D(gross) * D("0.05"))
        return gross, tax, gross + tax
    if mode == "incl":
        net = half_up(D(gross) / D("1.05"))
        return net, gross - net, gross
    return None, None, gross


