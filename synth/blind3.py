class Plan:
    def __init__(self, seed: int):
        self.rng = random.Random(seed)
        self.docs: list[dict] = []
        self.used_no: set[str] = set()
        self.used_files: set[tuple] = set()
        self.clients: dict[str, dict] = {}
        self.seller_ubn: dict[str, str] = {}
        self.seller_addr: dict[str, str] = {}

    def ubn(self, kind: str) -> str:
        """both: valid under old and new rule; new_only: valid only under the 2023 rule; seven: 7th digit 7 and valid
        only through the 'counts as 1' case."""
        r = self.rng
        while True:
            p = f"{r.randrange(10 ** 7):07d}"
            if kind == "seven":
                p = p[:6] + "7"
            cands = [p + str(x) for x in range(10)]
            if kind == "both":
                ok = [c for c in cands if ubn_ok(c, 10)]
            elif kind == "new_only":
                ok = [c for c in cands if ubn_ok(c, 5) and not ubn_ok(c, 10)]
            else:
                ok = [c for c in cands if ubn_ok(c, 5) and ubn_sum(c) % 5 != 0]
            if ok:
                return r.choice(ok)

    def typo(self, good: str) -> str:
        while True:
            i = self.rng.randrange(8)
            c = good[:i] + str((int(good[i]) + self.rng.randrange(1, 10)) % 10) + good[i + 1:]
            if not ubn_ok(c, 5):
                return c

    def transpose(self, good: str) -> str:
        for _ in range(200):
            i = self.rng.randrange(7)
            if good[i] != good[i + 1]:
                c = good[:i] + good[i + 1] + good[i] + good[i + 2:]
                if not ubn_ok(c, 5):
                    return c
        raise RuntimeError("no failing transposition")

    def inv_no(self) -> str:
        while True:
            s = "".join(self.rng.choice("ABCDEFGHJKLMNPQRSTUVWXYZ") for _ in range(2)) + f"{self.rng.randrange(10 ** 8):08d}"
            if s not in self.used_no:
                self.used_no.add(s)
                return s

    def fname(self, cid: str, month: str, shot: date) -> str:
        while True:
            f = f"IMG_{shot:%Y%m%d}_{self.rng.randrange(7, 22):02d}{self.rng.randrange(60):02d}{self.rng.randrange(60):02d}.jpg"
            if (cid, month, f) not in self.used_files:
                self.used_files.add((cid, month, f))
                return f

    def day(self, month: str) -> date:
        y, m = map(int, month.split("-"))
        last = (date(y + (m == 12), m % 12 + 1, 1) - timedelta(days=1)).day
        return date(y, m, self.rng.randint(1, last))

    def pick_items(self, key: str, cap: int | None, mode: str, filt=None):
        pool = [x for x in SELLERS[key][2] if filt is None or filt(x[0])]
        for _ in range(500):
            k = min(len(pool), self.rng.choice([1, 2, 2, 3]))
            chosen = self.rng.sample(pool, k)
            items = []
            for desc, (lo, hi, st), qs in chosen:
                q, u = self.rng.choice(qs), self.rng.randrange(lo, hi + 1, st)
                items.append({"desc": desc, "qty": q, "unit": u, "amount": q * u})
            if cap is None or amounts(mode, items)[2] <= cap:
                return items
        raise RuntimeError(f"cannot fit {key} under {cap}")

