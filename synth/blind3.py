# ------------------------------------------------------------------ UBN checksum (from the FIA notice text)

UBN_WEIGHTS = (1, 2, 1, 2, 1, 2, 4, 1)


def ubn_sum(u: str) -> int:
    """Sum of the digit sums of digit x weight (a product of 28 at the 7th digit counts as 2 + 8 = 10)."""
    return sum(p // 10 + p % 10 for p in (int(c) * w for c, w in zip(u, UBN_WEIGHTS)))


def ubn_ok(u: str, mod: int) -> bool:
    """mod=5: the 2023 rule; mod=10: the old rule. When the 7th digit is 7 its 10 may count as 1 or 0."""
    if len(u) != 8 or not u.isdigit():
        return False
    z = ubn_sum(u)
    return z % mod == 0 or (u[6] == "7" and (z + 1) % mod == 0)


# ------------------------------------------------------------------ fonts and drawing helpers

_fc: dict = {}


def F(kind: str, size: int):
    key = (kind, size)
    if key in _fc:
        return _fc[key]
    files = {"jh": "msjh.ttc", "jhb": "msjhbd.ttc", "jhl": "msjhl.ttc", "hk": "NotoSansHK-VF.ttf",
             "serif": "NotoSerifTC-VF.ttf", "serifb": "NotoSerifTC-VF.ttf", "kai": "kaiu.ttf", "ming": "mingliu.ttc",
             "mono": "consola.ttf", "monob": "consolab.ttf"}
    f = ImageFont.truetype(str(FONT_DIR / files[kind]), size)
    if kind in ("hk", "serif", "serifb"):
        f.set_variation_by_name("Bold" if kind == "serifb" else "Regular")
    _fc[key] = f
    return f


INK = (30, 30, 34)
BLUE = (28, 44, 120)
RED = (200, 36, 40)


def tw(d, s, f) -> float:
    return d.textlength(s, font=f)


def ctext(d, y, s, f, W, fill=INK):
    d.text(((W - tw(d, s, f)) / 2, y), s, font=f, fill=fill)


def rtext(d, xr, y, s, f, fill=INK):
    d.text((xr - tw(d, s, f), y), s, font=f, fill=fill)


def hand(img: Image.Image, x: float, y: float, s: str, size: int, rng: random.Random, color=BLUE) -> float:
    """Handwriting-like text: per-character size, angle and baseline jitter (Kai font). Returns the end x."""
    for ch in s:
        if ch == " ":
            x += size * 0.4
            continue
        f = F("kai", max(8, int(size * rng.uniform(0.92, 1.08))))
        tile = Image.new("RGBA", (size * 2, size * 2), (0, 0, 0, 0))
        td = ImageDraw.Draw(tile)
        td.text((size / 2, size / 2), ch, font=f, fill=color + (rng.randint(205, 255),))
        tile = tile.rotate(rng.uniform(-5, 5), resample=Image.BICUBIC)
        img.paste(tile, (int(x - size / 2), int(y - size / 2 + rng.uniform(-2, 2))), tile)
        x += td.textlength(ch, font=f) * rng.uniform(0.97, 1.08)
    return x


def hand_w(s: str, size: int) -> float:
    d = ImageDraw.Draw(Image.new("L", (4, 4)))
    return sum(size * 0.4 if c == " " else d.textlength(c, font=F("kai", size)) * 1.025 for c in s)


def hand_right(img, xr, y, s, size, rng, color=BLUE):
    hand(img, xr - hand_w(s, size), y, s, size, rng, color)


def barcode(d, x, y, w, h, rng, ink=INK):
    cx = x
    while cx < x + w:
        bw = rng.choice([1, 2, 2, 3])
        if rng.random() < 0.5:
            d.rectangle([cx, y, cx + bw - 1, y + h], fill=ink)
        cx += bw


def qr(d, x, y, s, rng, ink=INK):
    n = 21
    c = s / n
    for i in range(n):
        for j in range(n):
            if rng.random() < 0.5:
                d.rectangle([x + i * c, y + j * c, x + (i + 1) * c - 1, y + (j + 1) * c - 1], fill=ink)
    for fi, fj in ((0, 0), (n - 7, 0), (0, n - 7)):
        X, Y = x + fi * c, y + fj * c
        d.rectangle([X, Y, X + 7 * c, Y + 7 * c], fill="white")
        d.rectangle([X + c / 2, Y + c / 2, X + 6.5 * c, Y + 6.5 * c], outline=ink, width=max(1, int(c)))
        d.rectangle([X + 2 * c, Y + 2 * c, X + 5 * c, Y + 5 * c], fill=ink)


def dashed(d, y, x0, x1, ink=INK, step=8):
    for xx in range(int(x0), int(x1), step):
        d.line([xx, y, xx + step // 2, y], fill=ink, width=1)


def watermark(img: Image.Image) -> Image.Image:
    """Vertical 'synthetic' label in a strip added on the right edge, so it never covers printed content."""
    s = "SYNTHETIC · blind3 · 程式產生測試樣本"
    f = F("jh", 13)
    W, H = img.size
    out = Image.new("RGB", (W + 22, H), img.getpixel((W - 1, H - 1)))
    out.paste(img, (0, 0))
    w = int(tw(ImageDraw.Draw(out), s, f)) + 8
    tile = Image.new("RGBA", (w, 20), (0, 0, 0, 0))
    ImageDraw.Draw(tile).text((4, 1), s, font=f, fill=(140, 140, 140, 255))
    tile = tile.rotate(90, expand=True)
    out.paste(tile, (W + 1, max(4, H - tile.height - 12)), tile)
    return out


def seal(img: Image.Image, x, y, name, ubn, addr, title, rng, scale=1.0):
    """Red seller seal, rounded and drawn semi-transparent. The UBN on it is the seller's (possibly mistyped)."""
    W, H = int(250 * scale), int(150 * scale)
    layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    col = RED + (175,)
    d.rounded_rectangle([3, 3, W - 4, H - 4], radius=int(16 * scale), outline=col, width=max(2, int(4 * scale)))
    f1 = F("jhb", int(20 * scale))
    d.text(((W - tw(d, name, f1)) / 2, int(10 * scale)), name, font=f1, fill=col)
    f2 = F("jh", int(16 * scale))
    d.text((int(14 * scale), int(42 * scale)), "統一編號", font=f2, fill=col)
    d.text((int(92 * scale), int(39 * scale)), ubn, font=F("monob", int(21 * scale)), fill=col)
