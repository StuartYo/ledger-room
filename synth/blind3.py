def self_check(clients: list[dict], docs: list[dict]) -> list[str]:
    """Consistency of the hand-written answers with the README rule text, using only this module's own code."""
    cm = {c["id"]: c for c in clients}
    p0, p1 = (date.fromisoformat(x) for x in PERIOD)
    probs = []
    kind_limit = {"meal": "meal", "taxi": "taxi", "lodging": "lodging"}
    for d in docs:
        iss, c = set(d["issues"]), cm[d["client_id"]]
        bad = [u for u in (d["seller_ubn"], d["buyer_ubn"]) if u and not ubn_ok(u, 5)]
        if bool(bad) != ("UBN_CHECKSUM" in iss):
            probs.append(f"{doc_id(d)} UBN")
        dt = date.fromisoformat(d["date"])
        hdr_bad = d["invoice_period"] is not None and d["invoice_period"] != period_of(dt)
        if ((dt < p0 or dt > p1) or hdr_bad) != ("PERIOD_MISMATCH" in iss):
            probs.append(f"{doc_id(d)} PERIOD")
        kind = SELLERS[d["seller_key"]][1]
        lim = c["policy"][kind_limit[kind]] if kind in kind_limit else c["policy"]["any"]
        over = d["total"] > lim or d["total"] > c["policy"]["any"]
        if over != ("OVER_LIMIT" in iss):
            probs.append(f"{doc_id(d)} LIMIT {d['total']} vs {lim}")
        if (kind in ("gift", "staff", "car") or d["seller_key"] == "jiangzhe") != ("S19_NONDEDUCTIBLE" in iss):
            probs.append(f"{doc_id(d)} S19")
        if "S19_NONDEDUCTIBLE" in iss and d["buyer_ubn"] != c["ubn"]:
            probs.append(f"{doc_id(d)} S19 without the client's UBN")
        if d["buyer_ubn"] and d["buyer_ubn"] != c["ubn"] and "UBN_CHECKSUM" not in iss:
            probs.append(f"{doc_id(d)} buyer UBN of another company")
    # duplicates: invoice number, or seller + date + total
    def key(d):
        return d["invoice_no"] or f"{d['seller_name']}|{d['date']}|{d['total']}"
    groups: dict[str, list] = {}
    for d in docs:
        groups.setdefault(key(d), []).append(d)
    for k, g in groups.items():
        if len(g) == 1:
            if {"DUP_CROSS_MONTH", "DUP_CROSS_CLIENT"} & set(g[0]["issues"]):
                probs.append(f"{doc_id(g[0])} DUP label without a twin")
            continue
        if len(g) != 2:
            probs.append(f"{k}: {len(g)} copies")
            continue
        a, b = sorted(g, key=lambda x: "duplicate_of" in x)
        want = "DUP_CROSS_CLIENT" if a["client_id"] != b["client_id"] else "DUP_CROSS_MONTH"
        if want not in b["issues"] or (want == "DUP_CROSS_CLIENT") != (want in a["issues"]):
            probs.append(f"{k}: {want} labels")
    # also seller + date + total collisions between vouchers that do have invoice numbers
    sdt: dict[str, list] = {}
    for d in docs:
        sdt.setdefault(f"{d['seller_name']}|{d['date']}|{d['total']}", []).append(d)
    for k, g in sdt.items():
        if len(g) > 1 and not all("duplicate_of" in x or any("duplicate_of" in y and y["duplicate_of"] == doc_id(x)
                                                              for y in g) for x in g):
            probs.append(f"{k}: accidental seller+date+total match")
    return probs


def severity_note(d: dict) -> str | None:
    if d["layout"] == "taxi_slip" and {"DUP_CROSS_MONTH", "DUP_CROSS_CLIENT"} & set(d["issues"]):
        return SEVERITY_NOTES["taxi_dup"]
    if "PERIOD_MISMATCH" in d["issues"] and d["date"] < PERIOD[0]:
        return SEVERITY_NOTES["before"]
    if "S19_NONDEDUCTIBLE" in d["issues"] and SELLERS[d["seller_key"]][1] == "meal":
        return SEVERITY_NOTES["meal"]
    return None


def sanity(path: Path) -> dict:
    """Open the image and check its size only. Nothing is read or judged."""
    with Image.open(path) as im:
        im.load()
        w, h = im.size
        ok = im.format == "JPEG" and 300 <= min(w, h) and max(w, h) <= 2400
    return {"w": w, "h": h, "ok": ok}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def render_all(docs: list[dict], out: Path) -> dict[str, str]:
    hashes = {}
    for d in docs:
        p = out / "clients" / d["client_id"] / d["month"] / d["file"]
        p.parent.mkdir(parents=True, exist_ok=True)
        rng = random.Random(d["photo_seed"] ^ 0xB11D3)
        img = photograph(RENDER[d["layout"]](d, rng), d)
        img.save(p, "JPEG", quality=88)
        hashes[doc_id(d)] = sha(p)
    return hashes


def write() -> None:
    if FROZEN.exists():
        raise SystemExit(f"{FROZEN.relative_to(ROOT)} exists: blind3 is frozen and must not be regenerated.")
    clients, docs = plan()
    probs = self_check(clients, docs)
    if probs:
        raise SystemExit("blind3 answers are inconsistent:\n" + "\n".join(probs))
    out = ROOT / "data" / SET_NAME
    if out.exists() and any(out.rglob("*")):
        raise SystemExit(f"{out} is not empty")
    (out / "clients").mkdir(parents=True, exist_ok=True)
    (out / "clients.json").write_text(json.dumps({
        "synthetic": True,
        "note": "All companies, UBNs and documents are synthetic, generated by synth/blind3.py (author-written "
                "program; the author knows the rules).",
        "set": SET_NAME, "seed": SEED, "layout_family": LAYOUT_FAMILY, "clients": clients},
        ensure_ascii=False, indent=2), encoding="utf-8")
    hashes = render_all(docs, out)
    checks = {k: sanity(out / "clients" / k) for k in hashes}
    bad = [k for k, v in checks.items() if not v["ok"]]
    if bad:
        raise SystemExit(f"image sanity check failed: {bad}")
    recs = []
    for d in docs:
        recs.append({
            "doc_id": doc_id(d), "client_id": d["client_id"], "month": d["month"], "sha256": hashes[doc_id(d)],
            "synthetic": True, "issues": d["issues"], "duplicate_of": d.get("duplicate_of"), "mutant_of": None,
            "layout": d["layout"], "appearance": d["appearance"], "severity_note": severity_note(d),
            "truth": truth(d),
        })
    recs.sort(key=lambda x: x["doc_id"])
    now = datetime.now().astimezone().isoformat(timespec="seconds")
    expected = {
        "synthetic": True, "set": SET_NAME, "seed": SEED, "layout_family": LAYOUT_FAMILY,
        "generator": "synth/blind3.py", "frozen_at": now, "period": list(PERIOD),
        "design": ("Written by the author from the README rule table and the cited law articles. ledger_room/rules.py, "
                   "reader.py and pipeline.py were not read; the generator imports nothing from ledger_room or "
                   "synth/generate.py; no model and no ledger_room code was run on these files before freezing. "
                   "The author knows the six rules, so this is not an independent test set."),
        "n_docs": len(recs), "n_clean": sum(not x["issues"] for x in recs),
        "issue_counts": {t: sum(t in x["issues"] for x in recs) for t in ISSUE_TYPES},
        "docs": recs,
    }
    EXPECTED.write_text(json.dumps(expected, ensure_ascii=False, indent=1), encoding="utf-8")
    me = Path(__file__)
    frozen = {
        "synthetic": True, "set": SET_NAME, "frozen_at": now,
        "rule": "Frozen. Do not change any image, the answer key or clients.json. The first and only official run is "
                "made by the main session on the B70 host; record it, do not re-run after changes.",
        "pre_freeze_checks": "image open + size only (no OCR, no model, no ledger_room code)",
        "generator": {"path": "synth/blind3.py", "sha256": sha(me)},
        "expected": {"path": "eval/expected_blind3.json", "sha256": sha(EXPECTED)},
        "clients_json": {"path": "data/blind3/clients.json", "sha256": sha(out / "clients.json")},
        "images": {k: {"sha256": v, **{kk: checks[k][kk] for kk in ("w", "h")}} for k, v in sorted(hashes.items())},
    }
    FROZEN.write_text(json.dumps(frozen, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"blind3: {len(recs)} docs, {expected['n_clean']} clean, issues {expected['issue_counts']}; frozen.")


def verify() -> int:
    """Re-render into a temp folder and compare with the frozen hashes (rendering only, nothing is read or judged)."""
    frozen = json.loads(FROZEN.read_text(encoding="utf-8"))
    clients, docs = plan()
    with tempfile.TemporaryDirectory() as tmp:
        hashes = render_all(docs, Path(tmp))
    want = {k: v["sha256"] for k, v in frozen["images"].items()}
    gen_same = sha(Path(__file__)) == frozen["generator"]["sha256"]
    same = hashes == want
    print(f"images identical: {same}; generator unchanged: {gen_same}")
    return 0 if same else 1


def preview(out: Path) -> None:
    """Render every document into a scratch folder for a visual check before freezing (nothing is written to data/)."""
    clients, docs = plan()
    probs = self_check(clients, docs)
    print("; ".join(probs) or "self-check ok")
    render_all(docs, out)
    for d in docs:
        print(doc_id(d), d["layout"], d["issues"], d["total"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--preview", type=Path, help="render into this scratch folder only")
    a = ap.parse_args()
    if a.verify:
        sys.exit(verify())
    if a.preview:
        preview(a.preview)
        return
    write()


if __name__ == "__main__":
    main()
