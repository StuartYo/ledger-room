def plan() -> tuple[list[dict], list[dict]]:
    P = G.Planner(SEED, "A", SET_NAME)
    rng = P.rng
    clients = []
    for i, (cid, name, ind, addr) in enumerate(CLIENTS_H):
        clients.append({"id": cid, "name": name, "industry": ind, "address": addr,
                        "ubn": P.ubn("new_only" if i == 1 else "seven" if i == 2 else "both"),
                        "period": list(G.PERIOD),
                        "policy": {"meal": rng.choice([1500, 2000, 2500]), "taxi": rng.choice([800, 1000, 1200]),
                                   "lodging": rng.choice([3200, 3500, 3600]), "any": rng.choice([30000, 40000, 50000])}})
    for k in G.SELLERS:
        P.seller_ubn[k] = P.ubn(rng.choice(["both", "both", "new_only", "seven"]))
    docs = []
    for idx, (typ, var, fam, dtype) in enumerate(SLOTS):
        c = clients[idx % len(clients)]
        key = rng.choice([k for k in SELLERS_BY_TYPE[dtype] if dtype in G.SELLERS[k][1]])
        kind = G.SELLERS[key][2]
        cap = c["policy"][kind] if kind in ("meal", "taxi", "lodging") else c["policy"]["any"]
        month = rng.choice(["2026-09", "2026-10"])
        d = P.rand_date(f"{month}-01", f"{month}-{30 if month.endswith('09') else 31}")
        doc = P.make(c, key, doc_type=dtype, d=d, max_total=int(cap * 0.8), item_filter=lambda s: "家用" not in s)
        doc.update(slot=idx, damage=typ, variant=var, family=fam)
        docs.append(doc)
    return clients, docs


