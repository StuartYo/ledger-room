def build(doc: dict) -> tuple[Image.Image, dict]:
    rng = random.Random(doc["photo_seed"] ^ 0xD4A3)
    page, log = render_clean(doc)
    occ = occurrences(doc, log)
    truth = G.truth_fields(doc)
    readable = {f: True for f in KEY_FIELDS if truth.get(f) is not None}
    meta = {"type": doc["damage"], "variant": doc["variant"], "layout_family": doc["family"]}
    if doc["damage"] in GLOBAL:
        severe = doc["variant"] == "severe"
        img = GLOBAL[doc["damage"]](page, rng, severe)
        meta.update(severity="severe" if severe else "moderate",
                    readability_basis="author eye check of the whole page")
        for f in EYE.get(doc["slot"], []):
            if f in readable:
                readable[f] = False
    else:
        D = apply_local(doc, page, log, occ, rng)
        for f in readable:
            if f == "doc_type" or not occ.get(f):
                continue
            ok = [bb for bb in occ[f] if bb not in D.destroyed and D.visible(bb) >= VISIBLE]
            readable[f] = bool(ok)
        meta.update(severity="local", readability_basis=f"computed: a printed copy at least {VISIBLE:.0%} uncovered "
                                                        "and not written over", notes=D.notes,
                    printed_copies={f: len(v) for f, v in occ.items() if v})
        img = mild_photo(D.img, rng)
    meta["fields_affected"] = sorted(f for f, v in readable.items() if not v)
    return img, {"degradation": meta, "human_readable": readable}


def doc_id(d):
    return f"{d['client_id']}/{d['month']}/{d['file']}"


def write(out_root: Path | None = None, preview: bool = False) -> None:
    clients, docs = plan()
    if not preview:
        probs = G.oracle_check(clients, docs)
        if probs:
            raise SystemExit("hard set: the clean vouchers are not clean:\n" + "\n".join(probs))
    out = out_root or ROOT / "data" / SET_NAME
    if out.exists():
        for p in sorted(out.rglob("*"), reverse=True):
            p.unlink() if p.is_file() else p.rmdir()
    (out / "clients").mkdir(parents=True)
    (out / "clients.json").write_text(json.dumps({
        "synthetic": True,
        "note": "All companies, UBNs and documents are synthetic, generated by synth/hard.py (layouts from "
                "synth/generate.py, damage drawn by code).",
        "set": SET_NAME, "seed": SEED, "clients": clients}, ensure_ascii=False, indent=2), encoding="utf-8")
    recs = []
    for d in docs:
        img, meta = build(d)
        p = out / "clients" / d["client_id"] / d["month"] / d["file"]
        p.parent.mkdir(parents=True, exist_ok=True)
        img.save(p, "JPEG", quality=88)
        expect_hold = not all(meta["human_readable"].values())
        recs.append({
            "doc_id": doc_id(d), "client_id": d["client_id"], "month": d["month"],
            "sha256": hashlib.sha256(p.read_bytes()).hexdigest(), "synthetic": True, "slot": d["slot"],
            "issues": [], "duplicate_of": None, "mutant_of": None,
            **meta, "expect_hold": expect_hold,
            "expected_outcome": "HOLD for a person (a key field cannot be read on the image)" if expect_hold
            else "read every key field right, or hold",
            "truth": G.truth_fields(d),
        })
        if preview:
            print(d["slot"], doc_id(d), d["damage"], d["variant"], d["family"], d["doc_type"],
                  meta["degradation"]["fields_affected"])
    recs.sort(key=lambda x: x["doc_id"])
    if preview:
        return
    expected = {
        "synthetic": True, "set": SET_NAME, "seed": SEED, "generator": "synth/hard.py",
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "purpose": "reading under capture damage; every voucher is clean (no planted issue), so any of the six "
                   "issue types raised here is a false alarm caused by a misread",
        "damage_types": TYPES, "key_fields": KEY_FIELDS,
        "readability_rule": f"local damage: a field is readable when one printed copy is at least {VISIBLE:.0%} "
                            "uncovered and not written over (computed from the recorded print positions); "
                            "whole-page damage: author's eye check (EYE in synth/hard.py)",
        "n_docs": len(recs), "n_expect_hold": sum(r["expect_hold"] for r in recs),
        "by_type": {t: sum(r["degradation"]["type"] == t for r in recs) for t in TYPES},
        "docs": recs,
    }
    (ROOT / "eval" / "expected_hard.json").write_text(json.dumps(expected, ensure_ascii=False, indent=1),
                                                       encoding="utf-8")
    print(f"hard: {len(recs)} docs, {expected['n_expect_hold']} expected to be held, by type {expected['by_type']}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=Path, help="render into this scratch folder only")
    a = ap.parse_args()
    if a.preview:
        write(a.preview, preview=True)
    else:
        write()


if __name__ == "__main__":
    main()
