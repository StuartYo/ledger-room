class TextLog:
    """Records every text call on a page-sized canvas, and where seals are pasted, while generate.py renders."""

    def __init__(self):
        self.items: list[tuple[str, tuple, object]] = []
        self.seals: list[tuple] = []

    def __enter__(self):
        self._text, self._stamp = ImageDraw.ImageDraw.text, G.stamp
        log = self

        def text(dself, xy, text, *a, **k):
            try:
                if dself.im.size[0] >= 400 and dself.im.size[1] >= 600 and isinstance(text, str):
                    log.items.append((text, tuple(dself.textbbox(xy, text, font=k.get("font"))), k.get("font")))
            except Exception:
                pass
            return log._text(dself, xy, text, *a, **k)

        def stamp(img, x, y, doc, family, rng):
            log._stamp(img, x, y, doc, family, rng)
            log.seals.append((int(x), int(y) + 30, int(x) + 300, int(y) + 110))   # the UBN line of the seal

        ImageDraw.ImageDraw.text = text
        G.stamp = stamp
        return self

    def __exit__(self, *exc):
        ImageDraw.ImageDraw.text = self._text
        G.stamp = self._stamp


