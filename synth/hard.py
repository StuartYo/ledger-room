"""Hard set for Ledger Room: clean synthetic vouchers with capture problems that break OCR. EVERYTHING HERE IS SYNTHETIC.

Every company, UBN, invoice number, amount and image is generated by code (synth/generate.py's planner and layouts,
drawn with Pillow; the damage below is drawn with Pillow and numpy). No real people, no real business records, no
AI-generated images, no photos of real paper. Any match with a real business is coincidental.

What it is for: the synthetic sets so far are clean prints, and on them OCR alone scores the same as OCR + the vision
model. Here every document is a clean voucher (no planted issue) that is then damaged in one way a phone photo of
real paper often is:

  handwritten     a handwritten correction over the total (white-out + pen), or a digit written over another
  crease_shadow   crumpled paper (warped fold lines, shading) and a cast shadow
  perspective     a steep, skewed angle; the severe ones are also taken from far away
  stamp_pen       a red PAID stamp, a pen circle or tick over the total, a marker scribble, a dark stamp
  thermal_fade    faded thermal paper (e-invoices only)
  low_light_blur  dim light, sensor noise, defocus or motion blur
  occlusion       a finger or another receipt over part of the page

The answer key marks, for each key field, whether a person can still read it on the image:
  * local damage (pen, stamp, finger, other receipt, white-out): computed from where the field is printed. The
    renderers of synth/generate.py are run unchanged while their text calls are recorded, so the code knows every
    place a value is printed (the total also in 大寫, the seller UBN also on the seal). A field stays readable when
    at least one printed copy is at least 70% uncovered and not written over.
  * whole-page damage: "moderate" pages were checked by eye by the author and every key field is readable; "severe"
    pages were checked by eye and the fields listed in EYE below were judged unreadable.
A document with any unreadable key field should go to a person (expect_hold); reading it right is not expected.

Usage:  python -m synth.hard            # writes data/hard and eval/expected_hard.json
        python -m synth.hard --preview DIR
"""
