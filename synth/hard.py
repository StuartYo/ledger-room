def render_clean(doc: dict) -> tuple[Image.Image, TextLog]:
    rng = random.Random(doc["photo_seed"] ^ 0x5EED)
    with TextLog() as log:
        img = RENDER[doc["family"]][doc["doc_type"]](doc, doc["family"], rng)
    return img.convert("RGB"), log


def _tok(s: str, tok: str) -> bool:
    return re.search(r"(?<![\d,])" + re.escape(tok) + r"(?![\d,])", s) is not None


def occurrences(doc: dict, log: TextLog) -> dict[str, list[tuple]]:
    """Every place a key field's value is printed (page coordinates, before any photo effect)."""
    occ: dict[str, list] = {f: [] for f in KEY_FIELDS}
    items = log.items
    dt = date.fromisoformat(doc["date"])
    roc = str(dt.year - 1911)
    for s, bb, _ in items:
        flat = s.replace("-", "").replace(" ", "")
        if doc["invoice_no"] and doc["invoice_no"][2:] in flat:
            occ["invoice_no"].append(bb)
        if doc["date"] in s or (roc in s and ("年" in s or "/" in s)):
            occ["date"].append(bb)
        for f in ("seller_ubn", "buyer_ubn"):
            if doc[f] and doc[f] in s:
                occ[f].append(bb)
        if _tok(s, f"{doc['total']:,}") or G.cn_amount(doc["total"]) in s:
            occ["total"].append(bb)
    occ["seller_ubn"] += list(log.seals)
    # a UBN drawn one digit per box (family A triplicate)
    if doc["buyer_ubn"] and not occ["buyer_ubn"]:
        singles = [(s, bb) for s, bb, _ in items if len(s) == 1 and s.isdigit()]
        for i in range(len(singles) - 7):
            if "".join(s for s, _ in singles[i:i + 8]) == doc["buyer_ubn"]:
                bbs = [bb for _, bb in singles[i:i + 8]]
                occ["buyer_ubn"].append((min(b[0] for b in bbs), min(b[1] for b in bbs),
                                         max(b[2] for b in bbs), max(b[3] for b in bbs)))
    # net and tax: the value on the same row as its label
    for f, labels in (("net", ("銷售額",)), ("tax", ("稅額", "營業稅"))):
        if doc[f] is None:
            continue
        labs = [bb for s, bb, _ in items if any(k in s for k in labels) and not (f == "tax" and "銷售額" in s)]
        for s, bb, _ in items:
            if _tok(s, f"{doc[f]:,}") and any(abs((bb[1] + bb[3]) / 2 - (lb[1] + lb[3]) / 2) < 14 for lb in labs):
                occ[f].append(bb)
    return occ


# ------------------------------------------------------------------ local damage (page coordinates)

PEN_BLUE = (25, 45, 140)


class Damage:
    def __init__(self, img: Image.Image, rng: random.Random):
        self.img = img
        self.rng = rng
        self.mask = np.zeros((img.height, img.width), dtype=bool)    # opaque cover
        self.destroyed: list[tuple] = []                             # printed copies written over
        self.notes: list[str] = []

    def cover(self, layer: Image.Image, xy: tuple[int, int]):
        """Paste an RGBA layer and add its opaque part to the cover mask."""
        self.img.paste(layer, xy, layer)
        a = np.array(layer.split()[-1]) > 200
        x, y = xy
        h, w = a.shape
        x0, y0, x1, y1 = max(0, x), max(0, y), min(self.img.width, x + w), min(self.img.height, y + h)
        if x1 > x0 and y1 > y0:
            self.mask[y0:y1, x0:x1] |= a[y0 - y:y1 - y, x0 - x:x1 - x]

    def visible(self, bb) -> float:
        x0, y0, x1, y1 = (int(max(0, v)) for v in bb)
        x1, y1 = min(x1, self.img.width), min(y1, self.img.height)
        if x1 <= x0 or y1 <= y0:
            return 0.0
        return 1.0 - float(self.mask[y0:y1, x0:x1].mean())


def white_out_and_write(D: Damage, bb, value: str, size: int):
    r = D.rng
    x0, y0, x1, y1 = bb
    w, h = int(x1 - x0 + 16), int(y1 - y0 + 12)
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(layer).rounded_rectangle([0, 0, w - 1, h - 1], radius=6, fill=(251, 251, 246, 255))
    layer = layer.filter(ImageFilter.GaussianBlur(0.8))
    D.img.paste(layer, (int(x0 - 8), int(y0 - 6)), layer)
    # the corrected value is written by hand over the white-out: still the printed value, so it stays readable
    hand(D.img, x0 - 4, y0 - 4 + r.uniform(-3, 3), value, size, r, PEN_BLUE)
    D.notes.append(f"white-out over {value!r}, rewritten by hand")


def overwrite_digit(D: Damage, s: str, bb, font, value: str):
    """Write a different digit over one digit of the printed value: a person cannot tell which one counts."""
    r = D.rng
    m = re.search(re.escape(value), s)
    if not m or font is None:
        return
    digits = [i for i in range(m.start(), m.end()) if s[i].isdigit()]
    i = digits[len(digits) // 2]
    d0 = ImageDraw.Draw(D.img)
    x = bb[0] + d0.textlength(s[:i], font=font)
    other = "7" if s[i] in "1" else "8" if s[i] in "036" else "1" if s[i] == "7" else "6" if s[i] in "589" else "9"
    size = int((bb[3] - bb[1]) * 1.8)
    for dx in (0, 1, 2):          # a heavy pen stroke over the printed digit
        hand(D.img, x - 4 + dx, bb[1] - 9, other, size, random.Random(r.random()), (20, 20, 30))
    d0.line([x - 5, bb[3] + 3, x + d0.textlength(s[i], font=font) + 5, bb[1] - 3], fill=(20, 20, 30), width=3)
    D.destroyed.append(bb)
    D.notes.append(f"digit {s[i]!r} of {value} overwritten with {other!r}")


def paid_stamp(D: Damage, center, dark=False, date_txt="115.10.20"):
    r = D.rng
    R = 78
    layer = Image.new("RGBA", (2 * R + 8, 2 * R + 8), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    col = (150, 20, 25, 245) if dark else (205, 30, 40, 140)
    d.ellipse([4, 4, 2 * R + 4, 2 * R + 4], outline=col, width=7)
    d.ellipse([18, 18, 2 * R - 10, 2 * R - 10], outline=col, width=2)
    f = G.font("sans_bold", 34)
    d.text((R + 4 - d.textlength("已付款", font=f) / 2, R - 34), "已付款", font=f, fill=col)
    f2 = G.font("sans_bold", 18)
    d.text((R + 4 - d.textlength(date_txt, font=f2) / 2, R + 10), date_txt, font=f2, fill=col)
    if dark:   # an over-inked stamp: the middle fills up with ink
        d.ellipse([24, 24, 2 * R - 16, 2 * R - 16], fill=(150, 20, 25, 235))
    layer = layer.rotate(r.uniform(-25, 25), resample=Image.BICUBIC)
    xy = (int(center[0] - R - 4), int(center[1] - R - 4))
    if dark:
        D.cover(layer, xy)
    else:
        D.img.paste(layer, xy, layer)
    D.notes.append("over-inked dark stamp" if dark else "red PAID stamp, see-through")


def pen_circle(D: Damage, bb):
    r = D.rng
    d = ImageDraw.Draw(D.img)
    cx, cy = (bb[0] + bb[2]) / 2, (bb[1] + bb[3]) / 2
    rx, ry = (bb[2] - bb[0]) / 2 + 14, (bb[3] - bb[1]) / 2 + 10
    pts = []
    for k in range(70):
        t = k / 60 * 2 * math.pi
        pts.append((cx + rx * math.cos(t) * r.uniform(0.97, 1.05), cy + ry * math.sin(t) * r.uniform(0.95, 1.08)))
    d.line(pts, fill=PEN_BLUE, width=3, joint="curve")
    d.line([bb[0] - 6, cy + r.uniform(-3, 3), bb[2] + 8, cy + r.uniform(-4, 4)], fill=PEN_BLUE, width=2)
    D.notes.append("pen loop around the total and a line through it")


def pen_tick(D: Damage, bb):
    d = ImageDraw.Draw(D.img)
    x0, y0, x1, y1 = bb
    d.line([(x0 - 4, (y0 + y1) / 2), (x0 + (x1 - x0) * 0.35, y1 + 6), (x1 + 10, y0 - 14)], fill=PEN_BLUE, width=4,
           joint="curve")
    D.notes.append("pen tick across the total")


def scribble(D: Damage, bb):
    r = D.rng
    x0, y0, x1, y1 = (int(v) for v in bb)
    w, h = x1 - x0 + 20, y1 - y0 + 16
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    for k in range(0, w, 3):
        d.line([(k, r.uniform(0, 4)), (k + r.uniform(-6, 6), h - r.uniform(0, 4))], fill=(15, 15, 20, 255), width=4)
    D.cover(layer, (x0 - 10, y0 - 8))
    D.notes.append("black marker scribble")


def finger(D: Damage, target, from_edge: str):
    """A fingertip reaching in from one edge of the page to the target box."""
    r = D.rng
    W, H = D.img.size
    tx, ty = (target[0] + target[2]) / 2, (target[1] + target[3]) / 2
    width = max(70, int((target[3] - target[1]) * 2.2), int(min(W, H) * 0.16))
    layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    sx, sy = {"right": (W + 40, ty + r.uniform(-30, 30)), "bottom": (tx + r.uniform(-40, 40), H + 40),
              "left": (-40, ty), "top": (tx, -40)}[from_edge]
    skin = (222, 170, 138, 255)
    steps = 40
    for k in range(steps + 1):
        t = k / steps
        x, y = sx + (tx - sx) * t, sy + (ty - sy) * t
        rad = width / 2 * (0.92 + 0.08 * (1 - t))
        d.ellipse([x - rad, y - rad, x + rad, y + rad], fill=skin)
    # nail and shading
    vx, vy = tx - sx, ty - sy
    n = math.hypot(vx, vy) or 1
    nx, ny = tx - vx / n * width * 0.18, ty - vy / n * width * 0.18
    d.ellipse([nx - width * 0.26, ny - width * 0.22, nx + width * 0.26, ny + width * 0.22], fill=(236, 200, 182, 255))
    shade = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(shade).line([(sx, sy), (tx, ty)], fill=(150, 95, 70, 120), width=int(width * 0.35))
    layer = Image.alpha_composite(layer, Image.composite(shade, Image.new("RGBA", (W, H)), layer.split()[-1]))
    layer = layer.filter(ImageFilter.GaussianBlur(1.6))
    D.cover(layer, (0, 0))
    D.notes.append(f"finger from the {from_edge} edge")


