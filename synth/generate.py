def font(kind: str, size: int):
    key = (kind, size)
    if key in _font_cache:
        return _font_cache[key]
    if kind in ("sans", "sans_bold", "sans_medium"):
        f = ImageFont.truetype(str(FONT_DIR / "NotoSansTC-VF.ttf"), size)
        f.set_variation_by_name({"sans": "Regular", "sans_bold": "Bold", "sans_medium": "Medium"}[kind])
    elif kind in ("serif", "serif_bold"):
        f = ImageFont.truetype(str(FONT_DIR / "NotoSerifTC-VF.ttf"), size)
        f.set_variation_by_name("Bold" if kind == "serif_bold" else "Regular")
    elif kind == "kai":
        f = ImageFont.truetype(str(FONT_DIR / "kaiu.ttf"), size)
    elif kind == "ming":
        f = ImageFont.truetype(str(FONT_DIR / "mingliu.ttc"), size)
    else:
        raise KeyError(kind)
    _font_cache[key] = f
    return f


