def truth_fields(doc: dict) -> dict:
    return {
        "doc_type": doc["doc_type"],
        "invoice_no": doc["invoice_no"],
        "date": doc["date"],
        "invoice_period": doc["invoice_period"],
        "seller_name": doc["seller_name"],
        "seller_ubn": doc["seller_ubn"],
        "buyer_name": doc["buyer_name"],
        "buyer_ubn": doc["buyer_ubn"],
        "items": [{"desc": i["desc"], "qty": i["qty"], "amount": i["amount"]} for i in doc["items"]],
        "net": doc["net"], "tax": doc["tax"], "total": doc["total"],
        "note": doc["note"],
    }


def to_rule_doc(doc_id: str, client_id: str, month: str, f: dict) -> rules.Doc:
    return rules.Doc(
        doc_id=doc_id, client_id=client_id, month=month, doc_type=f.get("doc_type"),
        invoice_no=rules.norm_invoice_no(f.get("invoice_no")),
        date=date.fromisoformat(f["date"]) if f.get("date") else None,
        invoice_period=f.get("invoice_period"),
        seller_name=f.get("seller_name"), seller_ubn=f.get("seller_ubn"),
        buyer_name=f.get("buyer_name"), buyer_ubn=f.get("buyer_ubn"),
        items=[rules.Item(i.get("desc", ""), i.get("qty"), i.get("amount")) for i in f.get("items", [])],
        net=f.get("net"), tax=f.get("tax"), total=f.get("total"), note=f.get("note"),
        model_category=f.get("category"),
    )


def oracle_check(clients: list[dict], docs: list[dict]) -> list[str]:
    cmap = {c["id"]: c for c in clients}
    rdocs = [to_rule_doc(doc_id(d), d["client_id"], d["month"], truth_fields(d)) for d in docs]
    got = rules.issues_by_doc(rules.run_rules(rdocs, cmap))
    problems = []
    for d in docs:
        want = set(d["issues"])
        have = got.get(doc_id(d), set())
        if want != have:
            problems.append(f"{doc_id(d)} {d['seller_key']} planted={sorted(want)} rules={sorted(have)}")
    return problems


def doc_id(d: dict) -> str:
    return f"{d['client_id']}/{d['month']}/{d['file']}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--family", choices=["A", "B"], required=True)
    args = ap.parse_args()

    clients, docs = build_plan(args.set, args.seed, args.family)
    problems = oracle_check(clients, docs)
    if problems:
        raise SystemExit("planted answers disagree with the rule engine:\n" + "\n".join(problems))

    out = ROOT / "data" / args.set
    if out.exists():
        for p in sorted(out.rglob("*"), reverse=True):
            p.unlink() if p.is_file() else p.rmdir()
    (out / "clients").mkdir(parents=True)
    (out / "clients.json").write_text(json.dumps({
        "synthetic": True,
        "note": "All companies, UBNs and documents are synthetic, generated by synth/generate.py.",
        "set": args.set, "seed": args.seed, "layout_family": args.family,
        "clients": clients}, ensure_ascii=False, indent=2), encoding="utf-8")

    records = []
    for d in docs:
        p = out / "clients" / d["client_id"] / d["month"] / d["file"]
        p.parent.mkdir(parents=True, exist_ok=True)
        render(d, args.family).save(p, "JPEG", quality=88)
        records.append({
            "doc_id": doc_id(d),
            "client_id": d["client_id"],
            "month": d["month"],
            "sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
            "issues": d["issues"],
            "duplicate_of": d.get("duplicate_of"),
            "truth": truth_fields(d),
        })
    records.sort(key=lambda r: r["doc_id"])
    counts = {t: sum(t in r["issues"] for r in records) for t in rules.ISSUE_TYPES}
    expected = {
        "synthetic": True,
        "set": args.set, "seed": args.seed, "layout_family": args.family,
        "frozen_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "n_docs": len(records), "n_clean": sum(not r["issues"] for r in records),
        "issue_counts": counts,
        "docs": records,
    }
    (ROOT / "eval").mkdir(exist_ok=True)
    (ROOT / "eval" / f"expected_{args.set}.json").write_text(
        json.dumps(expected, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{args.set}: {len(records)} docs, {expected['n_clean']} clean, issues {counts}")


if __name__ == "__main__":
    main()
