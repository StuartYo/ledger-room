def text_w(draw, s, f):
    return draw.textlength(s, font=f)


def centered(draw, y, s, f, W, fill=INK):
    draw.text(((W - text_w(draw, s, f)) / 2, y), s, font=f, fill=fill)


def fake_barcode(draw, x, y, w, h, rng):
    cx = x
    while cx < x + w:
        bw = rng.choice([1, 1, 2, 3])
        if rng.random() < 0.55:
            draw.rectangle([cx, y, cx + bw - 1, y + h], fill=INK)
        cx += bw


def fake_qr(draw, x, y, s, rng):
    n = 25
    cell = s / n
    for i in range(n):
        for j in range(n):
            if rng.random() < 0.48:
                draw.rectangle([x + i * cell, y + j * cell, x + (i + 1) * cell, y + (j + 1) * cell], fill=INK)
    for (fi, fj) in [(0, 0), (n - 7, 0), (0, n - 7)]:
        X, Y = x + fi * cell, y + fj * cell
