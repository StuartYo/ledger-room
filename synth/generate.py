CN_DIGITS = "零壹貳參肆伍陸柒捌玖"


def cn_amount(n: int) -> str:
    """Chinese financial uppercase (大寫) for amounts < 100,000,000."""
    if n == 0:
        return "零元整"
    units = ["", "拾", "佰", "仟"]

    def four(x: int) -> str:
        s, zero = "", False
        for i in range(3, -1, -1):
            d = x // (10 ** i) % 10
            if d == 0:
                zero = bool(s)
            else:
                if zero:
                    s += "零"
                    zero = False
                s += CN_DIGITS[d] + units[i]
        return s

    wan, rest = divmod(n, 10000)
    out = ""
    if wan:
        out += four(wan) + "萬"
        if 0 < rest < 1000:
            out += "零"
    if rest:
        out += four(rest)
    return out + "元整"


def roc(d: date) -> int:
    return d.year - 1911


def period_of(d: date) -> str:
    m0 = d.month if d.month % 2 == 1 else d.month - 1
    return f"{d.year}-{m0:02d}/{d.year}-{m0 + 1:02d}"


def period_label(p: str) -> str:
    a, b = p.split("/")
    y = int(a[:4]) - 1911
    return f"{y}年{a[5:]}-{b[5:]}月"


