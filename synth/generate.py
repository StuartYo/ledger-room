def photo_effect(img: Image.Image, seed: int, family: str) -> Image.Image:
    rng = random.Random(seed)
    strong = family == "B"
    margin = rng.randint(30, 60) if strong else rng.randint(12, 26)
    bg_col = rng.choice([(118, 92, 66), (90, 96, 104), (160, 150, 132), (60, 64, 70)]) if strong \
        else rng.choice([(236, 236, 232), (226, 228, 230), (240, 236, 228)])
    W, H = img.size
    canvas = Image.new("RGB", (W + 2 * margin, H + 2 * margin), bg_col)
    noise = Image.effect_noise(canvas.size, 18 if strong else 6).convert("RGB")
    canvas = Image.blend(canvas, noise, 0.12 if strong else 0.04)
    canvas.paste(img, (margin, margin))
    angle = rng.uniform(-5, 5) if strong else rng.uniform(-1.5, 1.5)
    canvas = canvas.rotate(angle, resample=Image.BICUBIC, expand=False, fillcolor=bg_col)
    if strong:   # uneven light: darken one side
        # rotate the square 256x256 ramp first, then resize: no black corners, no hard bands
        grad = Image.linear_gradient("L").rotate(rng.choice([0, 90, 180, 270])).resize(canvas.size)
        dark = ImageEnhance.Brightness(canvas).enhance(0.72)
        canvas = Image.composite(canvas, dark, grad.point(lambda v: 150 + v * 105 // 255))
    canvas = ImageEnhance.Brightness(canvas).enhance(rng.uniform(0.9, 1.06) if strong else rng.uniform(0.97, 1.03))
    canvas = ImageEnhance.Contrast(canvas).enhance(rng.uniform(0.85, 1.05) if strong else 1.0)
    if strong or rng.random() < 0.3:
        canvas = canvas.filter(ImageFilter.GaussianBlur(rng.uniform(0.4, 0.9) if strong else 0.3))
    return canvas


def render(doc: dict, family: str) -> Image.Image:
    rng = random.Random(doc["photo_seed"] ^ 0x5EED)
    fn = {"e_invoice": render_e_invoice, "triplicate_invoice": render_triplicate, "receipt": render_receipt}
    img = fn[doc["doc_type"]](doc, family, rng)
    if doc.get("note"):
        sticky_note(img, doc["note"], rng, doc["doc_type"], family)
    return photo_effect(img, doc["photo_seed"], family)


