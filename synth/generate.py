class Planner:
    def __init__(self, seed: int, family: str, set_name: str):
        self.rng = random.Random(seed)
        self.family = family
        self.set_name = set_name
        self.used_numbers: set[str] = set()
        self.used_files: set[str] = set()
        self.docs: list[dict] = []
        self.seller_ubn: dict[str, str] = {}

    # -- ids
    def ubn(self, kind: str = "both") -> str:
        """kind: both = valid under old and new; new_only = valid only under 2023 rule; bad = fails new rule."""
        while True:
            p = f"{self.rng.randrange(10**7):07d}"
            cands = [p + str(d) for d in range(10)]
            if kind == "both":
                ok = [c for c in cands if ubnlib.is_valid_old(c)]
            elif kind == "new_only":
                ok = [c for c in cands if ubnlib.is_valid_new(c) and not ubnlib.is_valid_old(c)]
            elif kind == "seven":
                p = p[:6] + "7"
                cands = [p + str(d) for d in range(10)]
                ok = [c for c in cands if ubnlib.is_valid_new(c) and ubnlib.weighted_sum(c) % 5 != 0]
            else:
                ok = [c for c in cands if not ubnlib.is_valid_new(c)]
            if ok:
                return self.rng.choice(ok)

    def bad_variant(self, good: str) -> str:
        """Typo-style corruption of a valid UBN: change one digit so the 2023 rule fails."""
        while True:
            i = self.rng.randrange(8)
            d = str((int(good[i]) + self.rng.randrange(1, 10)) % 10)
            cand = good[:i] + d + good[i + 1:]
            if not ubnlib.is_valid_new(cand):
                return cand

    def invoice_no(self) -> str:
        while True:
            s = "".join(self.rng.choice("ABCDEFGHJKLMNPQRSTUVWXYZ") for _ in range(2)) + f"{self.rng.randrange(10**8):08d}"
            if s not in self.used_numbers:
                self.used_numbers.add(s)
                return s

    def filename(self) -> str:
        while True:
            f = f"IMG_{self.rng.randrange(1000, 9999)}.jpg"
            if f not in self.used_files:
                self.used_files.add(f)
                return f

    def rand_date(self, lo: str = PERIOD[0], hi: str = PERIOD[1]) -> date:
        a, b = date.fromisoformat(lo), date.fromisoformat(hi)
        return a + timedelta(days=self.rng.randrange((b - a).days + 1))

    # -- doc construction
    def make(self, client: dict, seller_key: str, *, doc_type: str | None = None, d: date | None = None,
             items: list[tuple[str, int, int]] | None = None, item_filter=None, b2b: bool | None = None,
             month: str | None = None, note: str | None = None, issues=(), max_total: int | None = None) -> dict:
        name, types, kind, pool = SELLERS[seller_key]
        doc_type = doc_type or self.rng.choice(types)
        d = d or self.rand_date()
        if items is None:
            for _ in range(200):
                cand = [x for x in pool if (item_filter is None or item_filter(x[0]))]
                k = min(len(cand), self.rng.choice([1, 2, 2, 3]))
                chosen = self.rng.sample(cand, k)
                items = [(desc, self.rng.choice(q), self.rng.randrange(lo, hi + 1, 10)) for desc, (lo, hi), q in chosen]
                total = self._totals(doc_type, items, b2b if b2b is not None else True)[2]
                if max_total is None or total <= max_total:
                    break
        if b2b is None:
            b2b = doc_type == "triplicate_invoice" or (doc_type == "e_invoice" and kind not in ("meal", "taxi"))
        if doc_type == "triplicate_invoice":
            b2b = True
        if doc_type == "receipt":
            b2b = False
        net, tax, total = self._totals(doc_type, items, b2b)
        doc = {
            "client_id": client["id"],
            "month": month or d.strftime("%Y-%m"),
            "file": self.filename(),
            "doc_type": doc_type,
            "invoice_no": self.invoice_no() if doc_type != "receipt" else None,
            "receipt_serial": f"No. {self.rng.randrange(1, 99999):05d}" if doc_type == "receipt" else None,
            "date": d.isoformat(),
            "time": f"{self.rng.randrange(8, 21):02d}:{self.rng.randrange(60):02d}:{self.rng.randrange(60):02d}",
            "invoice_period": period_of(d) if doc_type == "e_invoice" else None,
            "seller_key": seller_key,
            "seller_name": name,
            "seller_ubn": self.seller_ubn[seller_key],
            "seller_addr": f"{self.rng.choice(['臺北市', '新北市', '桃園市', '臺中市', '臺南市', '高雄市'])}"
                           f"{self.rng.choice(['中正區', '信義區', '北區', '東區', '西屯區', '前鎮區'])}"
                           f"虛構路 {self.rng.randrange(1, 300)} 號",
            "buyer_name": client["name"] if (b2b or doc_type == "receipt") else None,
            "buyer_ubn": client["ubn"] if b2b else None,
            "buyer_addr": client["address"] if doc_type == "triplicate_invoice" else None,
            "items": [{"desc": desc, "qty": q, "unit": u, "amount": q * u} for desc, q, u in items],
            "net": net, "tax": tax, "total": total,
            "note": note,
            "random_code": f"{self.rng.randrange(10000):04d}",
            "issues": sorted(set(issues)),
            "photo_seed": self.rng.randrange(10**9),
        }
        self.docs.append(doc)
        return doc

    @staticmethod
    def _totals(doc_type: str, items, b2b: bool):
        gross = sum(q * u for _, q, u in items)
        if doc_type == "triplicate_invoice":
            # triplicate: item amounts are pre-tax, 5% VAT added
            net = gross
            tax = round(net * 0.05)
            return net, tax, net + tax
        if doc_type == "e_invoice" and b2b:
            total = gross
            net = round(total / 1.05)
            return net, total - net, total
        return None, None, gross

    def duplicate(self, src: dict, *, client: dict | None = None, month: str | None = None, issues=()) -> dict:
        doc = copy.deepcopy(src)
        doc["file"] = self.filename()
        if client is not None:
            doc["client_id"] = client["id"]
        if month is not None:
            doc["month"] = month
        doc["issues"] = sorted(set(issues))
        doc["photo_seed"] = self.rng.randrange(10**9)   # re-photographed: different angle/light
        doc["duplicate_of"] = f"{src['client_id']}/{src['month']}/{src['file']}"
        self.docs.append(doc)
        return doc


def build_plan(set_name: str, seed: int, family: str) -> tuple[list[dict], list[dict]]:
    P = Planner(seed, family, set_name)
    rng = P.rng
    base = CLIENTS_A if family == "A" else CLIENTS_B
    clients = []
    for i, (cid, name, industry, addr) in enumerate(base):
        kind = "new_only" if i == 2 else ("seven" if i == 3 else "both")   # one client has a post-2023 UBN
        clients.append({
            "id": cid, "name": name, "industry": industry, "address": addr, "ubn": P.ubn(kind),
            "period": list(PERIOD),
            "policy": {
                "meal": rng.choice([1500, 2000, 2500]),
                "taxi": rng.choice([800, 1000, 1200]),
                "lodging": rng.choice([3200, 3500, 3600]),
                "any": rng.choice([30000, 40000, 50000]),
            },
        })
    # seller UBNs: some are new-rule-only (traps for software or models that still use mod 10)
    keys = list(SELLERS)
    trap_sellers = set(rng.sample(keys, 5))
    seven_sellers = set(rng.sample([k for k in keys if k not in trap_sellers], 2))
    for k in keys:
        P.seller_ubn[k] = P.ubn("new_only" if k in trap_sellers else "seven" if k in seven_sellers else "both")

    def lim(c, kind):
        return c["policy"][kind]

    def clean(c, month=None, small_ok=True):
        key = rng.choice(CLEAN_CLAIMABLE + (CLEAN_SMALL if small_ok else []))
        kind = SELLERS[key][2]
        cap = lim(c, kind) if kind in ("meal", "taxi", "lodging") else lim(c, "any")
        d = P.rand_date(f"{month}-01", f"{month}-{30 if month.endswith('09') else 31}") if month else None
        return P.make(c, key, d=d, max_total=int(cap * 0.8),
                      item_filter=lambda s: "家用" not in s)

    n_clean = 6 if family == "A" else 5
    for c in clients:
        for j in range(n_clean):
            clean(c, month="2026-09" if j % 2 == 0 else "2026-10")

    cs = clients
    # ---- UBN_CHECKSUM (seller typo x3, buyer typo on a triplicate x1, + family B: one more)
    for c, key in [(cs[0], "stationery"), (cs[1], "cafe"), (cs[3], "building")] + ([(cs[4], "print")] if family == "B" else []):
        doc = P.make(c, key, max_total=int(lim(c, "meal") * 0.7) if SELLERS[key][2] == "meal" else 20000,
                     item_filter=lambda s: "家用" not in s, issues=["UBN_CHECKSUM"])
        doc["seller_ubn"] = P.bad_variant(doc["seller_ubn"])
    doc = P.make(cs[2], "computer", doc_type="triplicate_invoice", max_total=20000, issues=["UBN_CHECKSUM"])
    doc["buyer_ubn"] = P.bad_variant(doc["buyer_ubn"])

    # ---- DUP_CROSS_MONTH: September voucher re-submitted in October
    sept_clean = [d for d in P.docs if d["month"] == "2026-09" and not d["issues"] and d["date"] < "2026-09-29"]
    n_dm = 3 if family == "A" else 2
    picks = rng.sample(sept_clean, n_dm)
    for src in picks:
        c = next(x for x in cs if x["id"] == src["client_id"])
        P.duplicate(src, month="2026-10", issues=["DUP_CROSS_MONTH"])

    # ---- DUP_CROSS_CLIENT: a B2C voucher (no buyer UBN) claimed by two clients
    b2c = [d for d in P.docs if not d["issues"] and d["buyer_ubn"] is None and d not in picks
           and "duplicate_of" not in d]
    for src in rng.sample(b2c, 2):
        others = [x for x in cs if x["id"] != src["client_id"]]
        tgt = rng.choice(others)
        src["issues"] = ["DUP_CROSS_CLIENT"]
        P.duplicate(src, client=tgt, issues=["DUP_CROSS_CLIENT"])

    # ---- S19_NONDEDUCTIBLE (claimable invoices to the client)
    s19 = [(cs[0], "gift", "用途：中秋送客戶"), (cs[1], "wine", "招待廠商"), (cs[2], "travel", None),
           (cs[3], "carservice", None), (cs[4], "mart", None)]
    if family == "B":
        s19 = [(cs[0], "wine", None), (cs[1], "gift", "送客戶"), (cs[2], "carservice", None),
               (cs[3], "travel", "員工旅遊"), (cs[4], "mart", None)]
    for c, key, note in s19:
        filt = (lambda s: "家用" in s) if key == "mart" else None
        P.make(c, key, b2b=True, note=note, item_filter=filt, max_total=int(lim(c, "any") * 0.6),
               issues=["S19_NONDEDUCTIBLE"])

    # ---- OVER_LIMIT
    c = cs[1]
    P.make(c, "seafood", doc_type="receipt",
           items=[("海鮮合菜 6人份", 1, lim(c, "meal") + 980), ("炒青菜", 1, 220)], issues=["OVER_LIMIT"])
    c = cs[4]
    P.make(c, "taxi", items=[("計程車資", 1, lim(c, "taxi") + 450)], issues=["OVER_LIMIT"])
    c = cs[0]
    P.make(c, "hotel", doc_type="e_invoice", b2b=True,
           items=[("住宿 標準雙人房 1晚", 2, (lim(c, "lodging") + 900) // 2 // 10 * 10)], issues=["OVER_LIMIT"])
    c = cs[3]
    q = math.ceil(lim(c, "any") / 1.05 / 6990) + 1
    P.make(c, "computer", doc_type="triplicate_invoice", items=[("27吋螢幕", q, 6990)], issues=["OVER_LIMIT"])

    # ---- PERIOD_MISMATCH
    c = cs[2]
    P.make(c, "taxi", d=date(2026, 7, 28), month="2026-09", max_total=int(lim(c, "taxi") * 0.7),
           issues=["PERIOD_MISMATCH"])
    c = cs[4]
    P.make(c, "stationery", doc_type="e_invoice", d=date(2026, 8, 30), month="2026-09", max_total=15000,
           issues=["PERIOD_MISMATCH"])
    c = cs[0]
    P.make(c, "building" if family == "A" else "print", doc_type="triplicate_invoice", d=date(2026, 11, 3),
           month="2026-10", max_total=15000, issues=["PERIOD_MISMATCH"])
    c = cs[3]
    doc = P.make(c, "courier", doc_type="e_invoice", d=date(2026, 9, 5) if family == "A" else date(2026, 10, 12),
                 issues=["PERIOD_MISMATCH"])
    doc["invoice_period"] = "2026-07/2026-08"   # printed header disagrees with the printed date

    return clients, P.docs


